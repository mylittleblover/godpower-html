    async function importRosterBackup(parsed) {
      if (
        !parsed ||
        parsed.format !== AVATAR_BACKUP_FORMAT ||
        parsed.schemaVersion !== 1 ||
        !Array.isArray(parsed.avatars)
      )
        return {
          rosterData: root.ClassroomRoster.validateRosterDocument(parsed),
          createdResources: [],
        };
      const rosterData = root.ClassroomRoster.validateRosterDocument(
        parsed.rosterData,
      );
      if (parsed.avatars.length > 2000)
        throw new Error("头像备份资源数量超出安全上限");
      const referenced = new Set(
        rosterData.students
          .map((student) => student.avatarResourceId)
          .filter(Boolean),
      );
      const avatarIds = new Set();
      const profileIds = new Set(
        rosterData.profiles.map((profile) => profile.userProfileId),
      );
      const classroomById = new Map(
        rosterData.classrooms.map((classroom) => [
          classroom.classroomId,
          classroom,
        ]),
      );
      const prepared = [];
      let totalBytes = 0;
      for (const entry of parsed.avatars) {
        if (
          !entry ||
          typeof entry.resourceId !== "string" ||
          avatarIds.has(entry.resourceId) ||
          !referenced.has(entry.resourceId)
        )
          throw new Error("头像备份存在重复、未引用或无效资源 ID");
        avatarIds.add(entry.resourceId);
        if (
          entry.subjectId !== "student-avatar" ||
          !profileIds.has(entry.profileId) ||
          !classroomById.has(entry.classroomId) ||
          !["image/png", "image/jpeg", "image/webp"].includes(entry.mimeType)
        )
          throw new Error("头像资源的profile、课堂或图片类型无效");
        const bytes = fromBase64(entry.bytesBase64);
        if (!bytes.byteLength || bytes.byteLength > 2 * 1024 * 1024)
          throw new Error("头像资源必须大于 0 且不超过 2 MiB");
        totalBytes += bytes.byteLength;
        if (totalBytes > MAX_AVATAR_BACKUP_BYTES)
          throw new Error("头像备份总大小不能超过 50 MiB");
        const ownerMatch = rosterData.students.some(
          (student) =>
            student.avatarResourceId === entry.resourceId &&
            student.classroomId === entry.classroomId,
        );
        if (!ownerMatch) throw new Error("头像资源与学生课堂不匹配");
        if ((await sha256(bytes)) !== entry.sha256?.toLowerCase())
          throw new Error(`头像内容校验失败：${entry.resourceId}`);
        const metadata = root.TeachingResource.validateFile(
          {
            ...entry,
            byteSize: bytes.byteLength,
            schemaVersion: 1,
          },
          bytes,
        );
        prepared.push({ metadata, bytes });
      }
      if (avatarIds.size !== referenced.size)
        throw new Error("头像备份缺少名单引用的图片数据");
      if (!prepared.length) return { rosterData, createdResources: [] };

      const avatarRepo = await getAvatarRepository();
      const existing = await avatarRepo.list();
      const existingById = new Map(
        existing.map((item) => [item.resourceId, item]),
      );
      const existingByHash = new Map(
        existing.map((item) => [item.sha256, item]),
      );
      const importedByHash = new Map();
      const mapping = new Map();
      const toCreate = [];
      for (const item of prepared) {
        const { metadata, bytes } = item;
        const sameId = existingById.get(metadata.resourceId);
        if (sameId) {
          const record = await avatarRepo.get(metadata.resourceId);
          if (
            sameId.sha256 === metadata.sha256 &&
            sameId.byteSize === metadata.byteSize &&
            sameId.subjectId === "student-avatar" &&
            sameId.classroomId === metadata.classroomId &&
            record?.blob.size === metadata.byteSize
          ) {
            mapping.set(metadata.resourceId, metadata.resourceId);
            continue;
          }
        }
        const sameHash = existingByHash.get(metadata.sha256);
        if (sameHash) {
          if (
            sameHash.subjectId !== "student-avatar" ||
            sameHash.classroomId !== metadata.classroomId
          )
            throw new Error("相同头像内容已属于其他课堂资源，未覆盖现有数据");
          mapping.set(metadata.resourceId, sameHash.resourceId);
          continue;
        }
        const batchDuplicate = importedByHash.get(metadata.sha256);
        if (batchDuplicate) {
          if (batchDuplicate.classroomId !== metadata.classroomId)
            throw new Error("相同头像不能跨课堂共用");
          mapping.set(metadata.resourceId, batchDuplicate.resourceId);
          continue;
        }
        const resourceId = sameId
          ? root.StableIdentity.createResourceId()
          : metadata.resourceId;
        const finalMetadata = root.TeachingResource.validateFile(
          { ...metadata, resourceId },
          bytes,
        );
        const file = new File([bytes], finalMetadata.fileName, {
          type: finalMetadata.mimeType,
        });
        toCreate.push({
          file,
          resourceId,
          profileId: finalMetadata.profileId,
          classroomId: finalMetadata.classroomId,
          subjectId: finalMetadata.subjectId,
          title: finalMetadata.title,
          tags: finalMetadata.tags,
          importedAt: finalMetadata.importedAt,
          expectedSha256: finalMetadata.sha256,
          expectedByteSize: finalMetadata.byteSize,
        });
        importedByHash.set(metadata.sha256, {
          resourceId,
          classroomId: metadata.classroomId,
        });
        mapping.set(metadata.resourceId, resourceId);
      }
      const createdResources = toCreate.length
        ? await avatarRepo.addBatch(toCreate)
        : [];
      for (const student of rosterData.students)
        if (student.avatarResourceId)
          student.avatarResourceId = mapping.get(student.avatarResourceId);
      return { rosterData, createdResources };
    }
    async function rollbackImportedResources(resources) {
      if (!resources.length) return;
      const avatarRepo = await getAvatarRepository();
      const failures = [];
      for (const resource of resources) {
        try {
          await avatarRepo.remove(resource.resourceId);
        } catch (error) {
          failures.push(`${resource.resourceId}: ${error.message}`);
        }
      }
      if (failures.length)
        throw new Error(`新头像回滚不完整：${failures.join("；")}`);
    }
    async function commitRosterImport(parsed) {
      const initialBytes = storage.getItem(repository.key);
      const initial = repository.read();
      if (!initial.ok || initial.revision !== revision)
        throw new Error("本地名单版本已变化，请重新打开工作区后导入");
      const result = await importRosterBackup(parsed);
      try {
        const latest = repository.read();
        if (
          !latest.ok ||
          latest.revision !== initial.revision ||
          storage.getItem(repository.key) !== initialBytes
        )
          throw new Error("名单在导入过程中已变化");
        const saved = repository.write(result.rosterData, {
          expectedRevision: initial.revision,
        });
        if (!saved.ok) throw new Error(saved.message || saved.code);
        documentData = saved.rosterData;
        revision = saved.revision;
        render();
        return result.createdResources.length;
      } catch (error) {
        try {
          await rollbackImportedResources(result.createdResources);
        } catch (rollbackError) {
          throw new Error(`${error.message}；${rollbackError.message}`);
        }
        throw new Error(`${error.message}；新建头像资源已回滚`);
      }
    }

