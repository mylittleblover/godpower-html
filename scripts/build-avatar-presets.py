"""Build the audited offline avatar catalog. Explicit maintenance command only.

Normal HTML builds never use the network. The checked-in source manifest owns
names and coverage; downloaded images are bounded, hashed and cached. A missing
image aborts before replacing either checked-in output, never silently dropping
existing presets.
"""
import base64
import concurrent.futures
import hashlib
import io
import json
import pathlib
import urllib.request
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
CACHE = ROOT / '.cache/avatar-presets'
CACHE.mkdir(parents=True, exist_ok=True)
manifest = json.loads((ROOT / 'scripts/data/avatar-preset-sources.json').read_text())


def fetch(url):
    request = urllib.request.Request(url, headers={
        'User-Agent': 'GodPower-Classroom/3.0 (offline avatar preset source audit)'})
    error = None
    for _ in range(3):
        try:
            return urllib.request.urlopen(request, timeout=30).read()
        except Exception as exc:
            error = exc
    raise error


def process(source):
    item = dict(source)
    cached = CACHE / (item.get('sha256', item['id']) + '.webp')
    if cached.exists():
        data = cached.read_bytes()
        if item.get('sha256') and hashlib.sha256(data).hexdigest() != item['sha256']:
            raise ValueError('cached thumbnail hash mismatch: ' + item['id'])
    else:
        raw = fetch(item['image'])
        if len(raw) > 15 * 1024 * 1024:
            raise ValueError('source image too large: ' + item['id'])
        try:
            original = Image.open(io.BytesIO(raw))
        except Exception as exc:
            raise ValueError("invalid source image: " + item["id"] + " " + item["image"]) from exc
        original.thumbnail((160, 160))
        out = Image.new('RGBA', (160, 160), (247, 250, 248, 255))
        out.alpha_composite(original.convert('RGBA'),
                            ((160-original.width)//2, (160-original.height)//2))
        stream = io.BytesIO()
        out.save(stream, format='WEBP', quality=82, method=6)
        data = stream.getvalue()
        item['sourceSha256'] = hashlib.sha256(raw).hexdigest()
        cached.write_bytes(data)
        # Retain raw hash next to a newly generated id-based cache.
        cached.with_suffix('.json').write_text(json.dumps({'sourceSha256': item['sourceSha256']}))
    if not item.get('sourceSha256'):
        item.update(json.loads(cached.with_suffix('.json').read_text()))
    if len(data) >= 30000:
        raise ValueError('thumbnail exceeds offline resource bound: ' + item['id'])
    if Image.open(io.BytesIO(data)).size != (160, 160):
        raise ValueError('invalid thumbnail dimensions: ' + item['id'])
    item.update(sha256=hashlib.sha256(data).hexdigest(), bytes=len(data),
                dataUrl='data:image/webp;base64,' + base64.b64encode(data).decode())
    return item


with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    items = list(pool.map(process, manifest['items']))
if len({item['id'] for item in items}) != len(items):
    raise ValueError('duplicate preset id')
items.sort(key=lambda item: manifest['categories'].index(item['category']))
catalog = {'schemaVersion': 1, 'categories': manifest['categories'], 'items': items}
provenance = {'schemaVersion': 2, 'sourceRosterCount': manifest['coverage']['smash']['entries'],
              'coverage': manifest['coverage'],
              'items': [{k: v for k, v in item.items() if k != 'dataUrl'} for item in items],
              'missing': manifest['coverage']['sonic']['missing']}
# Validate all resources before touching any release source.
(ROOT / 'src/resources/avatar-presets.js').write_text(
    '/* Offline presets; generated by scripts/build-avatar-presets.py. */\n'
    + 'const AvatarPresetCatalog = '
    + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';\n')
(ROOT / 'docs/AVATAR_PRESET_SOURCES.json').write_text(
    json.dumps(provenance, ensure_ascii=False, indent=2) + '\n')
print(json.dumps({'presets': len(items), 'thumbnailBytes': sum(x['bytes'] for x in items),
                  'categories': {c: sum(x['category'] == c for x in items) for c in manifest['categories']},
                  'sonicNameGaps': len(provenance['missing'])}, ensure_ascii=False))
