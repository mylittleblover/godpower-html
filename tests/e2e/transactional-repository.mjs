import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { launch } from '../fixtures/browser.mjs';
let source = '';
try { source = await readFile('src/infrastructure/indexeddb/repository.js', 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
const server = createServer((_, response) => { response.setHeader('Content-Type', 'text/html'); response.end('<!doctype html><title>Repository test</title>'); });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
try {
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.addScriptTag({ content: source + '\nwindow.repositoryApi = typeof TransactionalRepository === "undefined" ? null : TransactionalRepository;' });
  assert.equal(await page.evaluate(() => typeof window.repositoryApi?.open), 'function', 'transaction repository must expose open()');
  const results = await page.evaluate(async () => {
    const api = window.repositoryApi;
    const rows = [];
    const ensure = (condition, message) => { if (!condition) throw Error(message); };
    const failure = async (operation, code) => {
      try { await operation(); } catch (error) { ensure(error.code === code, `${code}: ${error.code}: ${error.message}`); return; }
      throw Error('expected failure: ' + code);
    };
    const name = 'isolated-transaction-test-' + crypto.randomUUID();
    let repo = await api.open({ name });
    const event = { eventId: 'cmd-1:1', commandId: 'cmd-1', type: 'ROUND_SETTLED', payload: { correct: true } };
    const command = { commandId: 'cmd-1', aggregateId: 'classroom-a', expectedRevision: 0, snapshot: { groups: [{ score: 2 }] }, events: [event] };
    const first = await repo.commit(command);
    ensure(first.revision === 1, 'initial revision');
    const duplicate = await repo.commit(command);
    ensure(duplicate.duplicate && duplicate.revision === 1, 'idempotent result');
    ensure((await repo.listEvents('classroom-a')).length === 1, 'one event');
    rows.push('single commit and exact retry');
    await failure(() => repo.commit({ ...command, snapshot: { groups: [{ score: 9 }] } }), 'COMMAND_REUSED');
    await failure(() => repo.commit({ ...command, commandId: 'stale', events: [], snapshot: { groups: [{ score: 9 }] } }), 'REVISION_CONFLICT');
    ensure((await repo.read('classroom-a')).snapshot.groups[0].score === 2, 'conflicts preserve score');
    rows.push('conflicting retry and stale revision');
    await failure(() => repo.commit({ commandId: 'cmd-2', aggregateId: 'classroom-a', expectedRevision: 1, snapshot: { groups: [{ score: 4 }] }, events: [{ ...event, commandId: 'cmd-2' }] }), 'TRANSACTION_ABORTED');
    ensure((await repo.read('classroom-a')).revision === 1, 'duplicate event aborts state write');
    ensure((await repo.listEvents('classroom-a')).length === 1, 'duplicate event aborts event write');
    rows.push('event failure rolls back entire commit');
    const mutable = { groups: [{ score: 4 }] };
    const pending = repo.commit({ commandId: 'cmd-3', aggregateId: 'classroom-a', expectedRevision: 1, snapshot: mutable });
    mutable.groups[0].score = 999;
    await pending;
    ensure((await repo.read('classroom-a')).snapshot.groups[0].score === 4, 'async hash cannot race caller mutations');
    rows.push('immutable async command input');
    repo.close();
    repo = await api.open({ name });
    ensure((await repo.read('classroom-a')).snapshot.groups[0].score === 4, 'reopen persisted snapshot');
    repo.close();
    rows.push('database reopen');
    const migrationName = name + '-migration';
    repo = await api.open({ name: migrationName });
    const migration = { migrationId: 'migration-1', sourceManifest: [{ key: 'old', sha256: 'abc' }], aggregateId: 'classroom-a', snapshot: { groups: [{ score: 17 }] }, archives: [{ archiveId: 'season-1', data: { score: 17 } }], resources: [{ resourceId: 'audio-1', bytes: new Uint8Array([1, 2, 3]).buffer }] };
    const importing = repo.importSnapshot(migration);
    new Uint8Array(migration.resources[0].bytes)[0] = 99;
    const imported = await importing;
    ensure(imported.complete, 'migration completes');
    ensure((await repo.importSnapshot(migration)).duplicate, 'migration retry');
    ensure(new Uint8Array((await repo.readResource('audio-1')).bytes).join() === '1,2,3', 'resource bytes preserved');
    ensure((await repo.readArchive('season-1')).data.score === 17, 'archive retained');
    await failure(() => repo.importSnapshot({ ...migration, sourceManifest: [{ key: 'old', sha256: 'changed' }] }), 'MIGRATION_REUSED');
    rows.push('atomic migration and source identity');
    repo.close();
    repo = await api.open({ name: name + '-failure' });
    await failure(() => repo.importSnapshot({ ...migration, resources: [{ resourceId: 'invalid', uncloneable: () => 1 }] }), 'TRANSACTION_ABORTED');
    ensure(await repo.read('classroom-a') === null, 'failed import leaves no classroom');
    ensure(await repo.readArchive('season-1') === null, 'failed import leaves no archive');
    ensure(await repo.getMigration('migration-1') === null, 'failed import leaves no receipt');
    await failure(() => repo.importSnapshot({ ...migration, resources: [{ resourceId: 'duplicate' }, { resourceId: 'duplicate' }] }), 'TRANSACTION_ABORTED');
    ensure(await repo.read('classroom-a') === null, 'duplicate resource rolls back classroom');
    ensure(await repo.readArchive('season-1') === null, 'duplicate resource rolls back archive');
    ensure(await repo.getMigration('migration-1') === null, 'duplicate resource rolls back receipt');
    rows.push('clone validation and mid-transaction resource failure leave all stores unchanged');
    repo.close();
    return rows;
  });
  await mkdir('artifacts/v3-migration', { recursive: true });
  await writeFile('artifacts/v3-migration/transactional-repository.json', JSON.stringify({ browser: browser.version(), results }, null, 2));
  for (const result of results) console.log('PASS', result);
} finally { await browser.close(); server.close(); }
